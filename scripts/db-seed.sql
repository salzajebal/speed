-- 테이블 생성

CREATE TABLE IF NOT EXISTS public.consultations (
    id integer NOT NULL,
    name text NOT NULL,
    phone text NOT NULL,
    age_range text,
    income_type text,
    amount text,
    created_at timestamp without time zone DEFAULT now() NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS public.consultations_id_seq
    AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;

ALTER SEQUENCE public.consultations_id_seq OWNED BY public.consultations.id;
ALTER TABLE ONLY public.consultations ALTER COLUMN id SET DEFAULT nextval('public.consultations_id_seq'::regclass);
ALTER TABLE ONLY public.consultations ADD CONSTRAINT IF NOT EXISTS consultations_pkey PRIMARY KEY (id);

CREATE TABLE IF NOT EXISTS public.settings (
    key text NOT NULL,
    value text,
    updated_at timestamp without time zone DEFAULT now()
);
ALTER TABLE ONLY public.settings ADD CONSTRAINT IF NOT EXISTS settings_pkey PRIMARY KEY (key);

